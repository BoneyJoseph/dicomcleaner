package org.bnel.dicom;

import com.pixelmed.dicom.*;
import java.nio.charset.StandardCharsets;
import java.text.Normalizer;
import java.time.LocalDate;
import java.time.format.DateTimeFormatter;
import java.util.*;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Non-blocking identifier check (defence in depth).
 *
 * The cleaner removes identifying fields by tag. This check looks at content instead: it collects
 * identifiers from every source file in the job, then searches every value retained in the cleaned
 * output (and printable text inside kept private payloads) for them. Findings are warnings only.
 *
 * Matching rules
 * - Person names: whole words only (so MARY does not match inside PRIMARY).
 * - Numeric identifiers (IDs, accession, phone, serial numbers; 4+ digits): every non-digit is
 *   stripped from both sides, then the identifier is searched inside the remaining digit stream, so
 *   705-693-123 is found inside "xh$jknl7056931236780nmjko".
 * - Dates: every source date is searched in YYYYMMDD, DDMMYYYY and MMDDYYYY digit form, so
 *   07-06-2026 is found inside "202606076799".
 * - Mixed letter/digit identifiers and institution names: searched after removing punctuation/spaces.
 * - UIDs generated by this app, standard DICOM UIDs, the operator's replacement name/ID and the
 *   synthetic replacement date(s) are skipped: the app wrote them itself.
 */
final class ResidualGuard {
    /** One retained value to check, captured at cleaning time. */
    record Retained(String series, String location, String text) {}
    /** One warning, aggregated over files. */
    record Finding(String series, String location, String kind, int files) {
        @Override public String toString() {
            return location + ": " + kind + (files > 1 ? " (" + files + " files)" : "");
        }
    }

    private static final Set<Integer> ID_TAGS = Set.of(0x00100010, 0x00100020, 0x00101000, 0x00101001,
        0x00101002, 0x00080050, 0x00181000, 0x00181002, 0x00200010, 0x00380010, 0x00401001, 0x00102154);
    private static final Set<String> TEXT_VRS = Set.of("PN", "LO", "SH", "LT", "ST", "UT", "UC", "UR", "AE", "AS", "CS", "UI");
    private static final Set<String> STOP_WORDS = Set.of("HOSPITAL", "MEDICAL", "CENTER", "CENTRE", "UNIVERSITY",
        "CLINIC", "HEALTH", "INSTITUTE", "DEPARTMENT", "RADIOLOGY", "IMAGING", "RESEARCH", "GENERAL", "SCIENCES");
    private static final Pattern SUSPICIOUS = Pattern.compile(
        "(?i)([A-Z0-9._%+-]+@[A-Z0-9.-]+\\.[A-Z]{2,}|https?://|(?:[A-Z]:\\\\|\\\\\\\\)[^ ]+|"
        + "(?:patient|mrn|dob|ssn|accession)[ _:#-]*[A-Z0-9]{3,})");
    private static final Pattern PRINTABLE = Pattern.compile("[\\x20-\\x7E]{4,}");
    private static final DateTimeFormatter YMD = DateTimeFormatter.ofPattern("uuuuMMdd");

    private final Set<String> nameWords = new HashSet<>();   // whole-word person-name parts
    private final Set<String> phrases = new HashSet<>();     // A-Z0-9 normalized identifiers containing a letter
    private final Set<String> digitIds = new HashSet<>();    // digit-only identifiers (4+ digits)
    private final Set<String> dates = new HashSet<>();       // 8-digit date variants
    private Set<String> generatedUids = Set.of();               // live view of UIDs this job generated
    private final Set<String> skipDates = new HashSet<>();
    private final Map<Retained, Integer> retained = new LinkedHashMap<>();   // de-duplicated across files

    static String normalize(String value) {
        return Normalizer.normalize(value, Normalizer.Form.NFKD).replaceAll("\\p{M}", "")
            .toUpperCase(Locale.ROOT).replaceAll("[^A-Z0-9]", "");
    }
    static String digits(String value) { return value.replaceAll("[^0-9]", ""); }
    static Set<String> words(String value) {
        String plain = Normalizer.normalize(value, Normalizer.Form.NFKD).replaceAll("\\p{M}", "").toUpperCase(Locale.ROOT);
        Set<String> out = new HashSet<>();
        for (String w : plain.split("[^A-Z]+")) if (!w.isEmpty()) out.add(w);
        return out;
    }

    /** Collect identifiers from one source file (before cleaning). */
    void collect(AttributeList source) {
        for (DicomIO.Row row : DicomIO.rows(source)) {
            int k = Policy.key(row.attribute().getTag());
            String vr = row.vr(), value = row.value();
            if (value.isBlank() || value.startsWith("Binary data")) continue;
            IdentifierPolicy.Category category = IdentifierPolicy.category(source, row.attribute());
            if (vr.equals("PN") || category == IdentifierPolicy.Category.PERSON) {
                for (String w : words(value)) if (w.length() >= 3) nameWords.add(w);
                addNumbers(value);
            } else if (ID_TAGS.contains(k) || category == IdentifierPolicy.Category.OTHER_ID
                    || category == IdentifierPolicy.Category.CONTACT || category == IdentifierPolicy.Category.TRIAL) {
                for (String part : value.split("\\\\")) { addPhrase(part); addNumbers(part); }
            } else if (category == IdentifierPolicy.Category.INSTITUTION) {
                for (String part : value.split("\\\\")) {
                    addPhrase(part);
                    for (String w : words(part)) if (w.length() >= 5 && !STOP_WORDS.contains(w)) phrases.add(w);
                }
            } else if (category == IdentifierPolicy.Category.DEVICE && row.name().toLowerCase(Locale.ROOT).contains("serial")) {
                for (String part : value.split("\\\\")) { addPhrase(part); addNumbers(part); }
            }
            if (vr.equals("DA") || vr.equals("DT")) for (String d : value.split("\\\\")) addDate(d);
            if (vr.equals("UI") && row.attribute().getTag().getGroup() != 2
                    && UniqueIdentifierAttribute.isTransient(row.attribute().getTag()))
                for (String uid : value.split("\\\\")) { String n = digits(uid); if (n.length() >= 10) digitIds.add(n); }
        }
    }
    private void addPhrase(String value) {
        String n = normalize(value);
        if (n.length() >= 4 && n.matches(".*[A-Z].*")) phrases.add(n);
    }
    private void addNumbers(String value) {
        for (String run : value.split("[^0-9 ./()-]+")) {          // keep formatted numbers like 705-693-123 together
            String n = digits(run);
            if (n.length() >= 4) digitIds.add(n);
        }
    }
    private void addDate(String raw) {
        String d = digits(raw);
        if (d.length() < 8) return;
        try {
            LocalDate date = LocalDate.parse(d.substring(0, 8), YMD);
            dates.add(date.format(YMD));
            dates.add(date.format(DateTimeFormatter.ofPattern("ddMMuuuu")));
            dates.add(date.format(DateTimeFormatter.ofPattern("MMdduuuu")));
        } catch (RuntimeException ignored) { }
    }

    void generated(Set<String> liveUids) { generatedUids = liveUids; }
    void skipDate(LocalDate date) {
        if (date == null) return;
        skipDates.add(date.format(YMD));
        skipDates.add(date.format(DateTimeFormatter.ofPattern("ddMMuuuu")));
        skipDates.add(date.format(DateTimeFormatter.ofPattern("MMdduuuu")));
    }

    /** Capture retained values of one cleaned file; they are checked after every source has been collected. */
    void capture(String series, AttributeList cleaned) {
        for (DicomIO.Row row : DicomIO.rows(cleaned)) {
            AttributeTag t = row.attribute().getTag();
            int k = Policy.key(t);
            if (t.getGroup() == 2 || k == 0x00100010 || k == 0x00100020) continue; // file meta / operator's replacement
            String location = row.name() + " (" + String.format("%04X,%04X", t.getGroup(), t.getElement()) + ")";
            if (t.isPrivate() && DicomIO.binary(row.vr())) {
                try {
                    byte[] bytes = row.attribute().getByteValues();
                    if (bytes != null) {
                        Matcher m = PRINTABLE.matcher(new String(bytes, StandardCharsets.ISO_8859_1));
                        StringBuilder text = new StringBuilder();
                        while (m.find()) text.append(m.group()).append(' ');
                        if (text.length() > 0) retained.merge(new Retained(series, location, text.toString()), 1, Integer::sum);
                    }
                } catch (DicomException ignored) { }
                continue;
            }
            if (!TEXT_VRS.contains(row.vr()) || row.value().isBlank()) continue;
            if (row.vr().equals("UI")) {
                boolean appOrStandard = true;
                for (String uid : row.value().split("\\\\"))
                    if (!uid.isBlank() && !generatedUids.contains(uid) && !uid.startsWith("1.2.840.10008.")) appOrStandard = false;
                if (appOrStandard) continue;
            }
            retained.merge(new Retained(series, location, row.value()), 1, Integer::sum);
        }
    }

    /** Check every captured value; returns aggregated findings (empty when nothing was found). */
    List<Finding> findings() {
        Set<String> dateTokens = new HashSet<>(dates);
        dateTokens.removeAll(skipDates);
        Map<List<String>, Integer> counts = new LinkedHashMap<>();
        for (Map.Entry<Retained, Integer> e : retained.entrySet()) {
            Retained r = e.getKey();
            for (String kind : kinds(r.text(), dateTokens)) counts.merge(List.of(r.series(), r.location(), kind), e.getValue(), Integer::sum);
        }
        List<Finding> out = new ArrayList<>();
        counts.forEach((key, n) -> out.add(new Finding(key.get(0), key.get(1), key.get(2), n)));
        return out;
    }
    private Set<String> kinds(String text, Set<String> dateTokens) {
        Set<String> kinds = new LinkedHashSet<>();
        Set<String> w = words(text);
        for (String name : nameWords) if (w.contains(name)) { kinds.add("contains a name from the source files"); break; }
        String alnum = normalize(text), digitStream = digits(text);
        for (String p : phrases) if (alnum.contains(p)) { kinds.add("contains an ID or institution text from the source files"); break; }
        for (String d : digitIds) if (digitStream.contains(d)) { kinds.add("contains a number from a source identifier"); break; }
        for (String d : dateTokens) if (digitStream.contains(d)) { kinds.add("contains a source date"); break; }
        if (SUSPICIOUS.matcher(text).find()) kinds.add("looks like an email, web address, file path or labelled ID");
        return kinds;
    }

    /** True when the chosen replacement name/ID itself contains an original identifier. */
    boolean replacementLooksIdentifying(String value) {
        return !kinds(value, dates).isEmpty();
    }
}
